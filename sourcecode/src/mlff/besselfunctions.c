double derivative_modifiedsphericalbesselfirst(int n, double x){
	double sinh_x = sinh(x);
    double cosh_x = cosh(x);

    double der, i_n_minus_1, i_n_plus_1;

    double n_double = n*1.0;
    if (n >15){
    	printf("n > 15 for derivative_modifiedsphericalbesselfirst not available\n");
    	exit(1);
    }

	if (n==0){
		der = sqrt(1.0/x)*cosh_x/sqrt(x) - sqrt(1/x)*sinh(x)/pow(x,3.0/2.0);
	} else {
		i_n_minus_1 =  modifiedsphericalbesselfirst(n-1, x);
		i_n_plus_1 =  modifiedsphericalbesselfirst(n+1, x);

		der = ((n_double)*i_n_minus_1 + (n_double+1.0)*i_n_plus_1)/(2.0*n_double+1.0);
	}

	return der;
}

