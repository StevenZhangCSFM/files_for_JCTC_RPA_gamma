void modifiedsphericalbesselfirst_l_01(double x, double *vals) {
    vals[0] =  sinh(x) / x;
    vals[1] = ((2.0 * cosh(x) - (2.0 *  sinh(x)) / x)) / (2.0 * x);
}

double modifiedsphericalbesselfirst(int n, double x) {

    double in_val[n+1];
    modifiedsphericalbesselfirst_l_01(x, in_val);

    if (n==0){
        return in_val[0];
    } else if (n==1){
        return in_val[1];
    } else {
        if (pow(x, n+1)< 1e-14){
            return 0;
        }
        for (int nidx = 2; nidx < n+1; nidx++){
            in_val[nidx] = in_val[nidx-2] - (2.0*nidx -1.0)/x * in_val[nidx-1];
        }
        return in_val[n];
    }
}


